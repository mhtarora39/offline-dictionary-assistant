"""Train a lightweight NER model (MiniLM / MobileBERT) for dictionary term extraction."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List

import numpy as np
import torch
from datasets import Dataset
from transformers import (
    AutoModelForTokenClassification,
    AutoTokenizer,
    DataCollatorForTokenClassification,
    Trainer,
    TrainingArguments,
)

LABEL_LIST = ["O", "B-TERM", "I-TERM"]
LABEL2ID = {label: i for i, label in enumerate(LABEL_LIST)}
ID2LABEL = {i: label for i, label in enumerate(LABEL_LIST)}

DEFAULT_MODEL_NAME = "nreimers/MiniLM-L6-H384-uncased"
DATA_DIR = Path(__file__).resolve().parent / "data"
OUTPUT_DIR = Path(__file__).resolve().parent / "model"


def load_jsonl(path: Path) -> List[Dict[str, Any]]:
    records = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                records.append(json.loads(line))
    return records


def tokenize_and_align_labels(examples, tokenizer):
    """Align word-level BIO tags with subword tokens generated by tokenizer."""
    tokenized_inputs = tokenizer(
        examples["tokens"],
        is_split_into_words=True,
        truncation=True,
        max_length=64,
    )

    labels = []
    for i, tags in enumerate(examples["tags"]):
        word_ids = tokenized_inputs.word_ids(batch_index=i)
        previous_word_idx = None
        label_ids = []
        for word_idx in word_ids:
            if word_idx is None:
                # Special token ([CLS], [SEP])
                label_ids.append(-100)
            elif word_idx != previous_word_idx:
                # First subword token for this word
                tag_str = tags[word_idx] if word_idx < len(tags) else "O"
                label_ids.append(LABEL2ID.get(tag_str, 0))
            else:
                # Subsequent subwords for the same word
                tag_str = tags[word_idx] if word_idx < len(tags) else "O"
                # If first was B-TERM, follow-up subwords are I-TERM
                tag_id = LABEL2ID.get(tag_str, 0)
                if tag_id == LABEL2ID["B-TERM"]:
                    tag_id = LABEL2ID["I-TERM"]
                label_ids.append(tag_id)
            previous_word_idx = word_idx
        labels.append(label_ids)

    tokenized_inputs["labels"] = labels
    return tokenized_inputs


def compute_metrics(p):
    predictions, labels = p
    predictions = np.argmax(predictions, axis=2)

    true_predictions = [
        [LABEL_LIST[p] for (p, l) in zip(prediction, label) if l != -100]
        for prediction, label in zip(predictions, labels)
    ]
    true_labels = [
        [LABEL_LIST[l] for (p, l) in zip(prediction, label) if l != -100]
        for prediction, label in zip(predictions, labels)
    ]

    total = sum(len(l) for l in true_labels)
    correct = sum(
        sum(p == l for p, l in zip(preds, lbls))
        for preds, lbls in zip(true_predictions, true_labels)
    )
    accuracy = correct / total if total > 0 else 0.0

    return {"accuracy": accuracy}


def main():
    parser = argparse.ArgumentParser(description="Train lightweight NER for term extraction")
    parser.add_argument("--model-name", type=str, default=DEFAULT_MODEL_NAME)
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--lr", type=float, default=5e-5)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    args = parser.parse_args()

    train_path = DATA_DIR / "train.jsonl"
    val_path = DATA_DIR / "val.jsonl"

    if not train_path.exists() or not val_path.exists():
        raise FileNotFoundError(
            f"Dataset not found at {DATA_DIR}. Run generate_dataset.py first."
        )

    print(f"Loading data from {DATA_DIR}...")
    train_raw = load_jsonl(train_path)
    val_raw = load_jsonl(val_path)

    train_ds = Dataset.from_list(train_raw)
    val_ds = Dataset.from_list(val_raw)

    print(f"Initializing tokenizer and model: {args.model_name}...")
    tokenizer = AutoTokenizer.from_pretrained(args.model_name)
    model = AutoModelForTokenClassification.from_pretrained(
        args.model_name,
        num_labels=len(LABEL_LIST),
        id2label=ID2LABEL,
        label2id=LABEL2ID,
    )

    print("Tokenizing datasets...")
    train_tokenized = train_ds.map(
        lambda x: tokenize_and_align_labels(x, tokenizer),
        batched=True,
    )
    val_tokenized = val_ds.map(
        lambda x: tokenize_and_align_labels(x, tokenizer),
        batched=True,
    )

    data_collator = DataCollatorForTokenClassification(tokenizer=tokenizer)

    device_str = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"Using device: {device_str.upper()}")

    training_args = TrainingArguments(
        output_dir=str(args.output_dir / "checkpoints"),
        eval_strategy="epoch",
        save_strategy="epoch",
        learning_rate=args.lr,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.batch_size,
        num_train_epochs=args.epochs,
        weight_decay=0.01,
        logging_steps=50,
        load_best_model_at_end=True,
        metric_for_best_model="accuracy",
        report_to="none",
    )

    trainer_kwargs = {
        "model": model,
        "args": training_args,
        "train_dataset": train_tokenized,
        "eval_dataset": val_tokenized,
        "data_collator": data_collator,
        "compute_metrics": compute_metrics,
    }

    # Support both transformers v4 (tokenizer) and v5+ (processing_class)
    import inspect
    init_params = inspect.signature(Trainer.__init__).parameters
    if "processing_class" in init_params:
        trainer_kwargs["processing_class"] = tokenizer
    else:
        trainer_kwargs["tokenizer"] = tokenizer

    trainer = Trainer(**trainer_kwargs)

    print("Starting training...")
    trainer.train()

    print(f"Saving fine-tuned model and tokenizer to {args.output_dir}...")
    model.save_pretrained(args.output_dir)
    tokenizer.save_pretrained(args.output_dir)
    print("Training complete!")


if __name__ == "__main__":
    main()
